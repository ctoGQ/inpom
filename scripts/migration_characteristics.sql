-- ============================================
-- INDEX FOR SEARCH
-- ============================================
CREATE INDEX IF NOT EXISTS idx_characteristics_name ON shop_characteristics_catalog(name);
CREATE INDEX IF NOT EXISTS idx_characteristics_category ON shop_characteristics_catalog(category);
CREATE INDEX IF NOT EXISTS idx_characteristics_active ON shop_characteristics_catalog(is_active);

-- ============================================
-- VIEW FOR SEARCHING CHARACTERISTICS
-- ============================================
CREATE OR REPLACE VIEW shop_characteristics_search AS
SELECT id, name, category
FROM shop_characteristics_catalog
WHERE is_active = TRUE
ORDER BY display_order ASC;
